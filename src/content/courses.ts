let questionIndex = 0;
function q(
  prompt: string,
  correct: string,
  wrong1: string,
  wrong2: string,
  explanation: string,
  critical = false,
): Question {
  const id = `question-${++questionIndex}`;
  const rotation = questionIndex % 3;
  const original = [correct, wrong1, wrong2];
  const options = original.slice(rotation).concat(original.slice(0, rotation));
  return {
    id,
    prompt,
    options,
    answer: (3 - rotation) % 3,
    explanation,
    critical,
  };
}
