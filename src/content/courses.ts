export function sekiPosition(toPlay: Color = 1) {
  const initial: { row: number; col: number; color: Color }[] = [];
  for (let row = 0; row < 5; row++)
    for (let col = 0; col < 5; col++) {
      if (col === 2 && (row === 1 || row === 3)) continue;
      initial.push({
        row,
        col,
        color: col < 2 || (col === 2 && row < 3) ? 1 : 2,
      });
    }
  return createPosition(5, 0, initial, toPlay);
}
